#!/usr/bin/env bash
# PreCompact: перед сжатием контекста напомнить сохранить состояние в
# .claude/checkpoint.md (gitignored). Read-only — возвращает напоминание
# через additionalContext, ничего не пишет сам.
cat <<'JSON'
{"additionalContext": "⚠️ PRECOMPACT: контекст будет сжат. Прочитай .claude/checkpoint.md если он есть, и запиши в него: (1) над какой задачей работаешь и её тикет, (2) что осталось сделать, (3) какой ритуал или скилл выполняешь и на каком шаге, (4) незавершённое, включая непройденную верификацию (/verify)."}
JSON
exit 0
